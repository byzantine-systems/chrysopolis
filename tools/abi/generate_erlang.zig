//! Erlang projection of the orchestration ABI: `orchestrator_abi.hrl` and `chryso_abi_codec.erl`.
//! Checkers come from the same checks.zig tables as the C headers, so both languages share
//! layout, precedence and reason classes. Output is written into a build directory, never committed.
const std = @import("std");
const abi = @import("orchestrator_abi");
const model = @import("model");
const checks = @import("checks");
const naming = @import("naming");

const Writer = std.Io.Writer;
const snake = naming.snake;
const camel = naming.camel;
const upper = naming.upper;

pub const RenderError = Writer.Error || error{ UnknownRecord, UnknownChecker, UnknownField };

/// Nominal generation types: a spec generation and a slot generation must never be interchanged.
const Nominal = struct { record: []const u8, field: []const u8, type_name: []const u8 };
const nominals = [_]Nominal{
    .{ .record = "RootStatusHeader", .field = "applied_spec_generation", .type_name = "spec_generation" },
    .{ .record = "SpecBank", .field = "generation", .type_name = "spec_generation" },
    .{ .record = "RootChildStatus", .field = "slot_generation", .type_name = "slot_generation" },
    .{ .record = "WorkerIdentityHeader", .field = "generation", .type_name = "slot_generation" },
    .{ .record = "WorkerStatusHeader", .field = "generation", .type_name = "slot_generation" },
    .{ .record = "JournalHeader", .field = "generation", .type_name = "slot_generation" },
    .{ .record = "JournalEntry", .field = "generation", .type_name = "slot_generation" },
};

fn nominalFor(record: []const u8, field: []const u8) ?[]const u8 {
    for (nominals) |item| {
        if (std.mem.eql(u8, item.record, record) and std.mem.eql(u8, item.field, field)) return item.type_name;
    }
    return null;
}

fn isReserved(name: []const u8) bool {
    return std.mem.startsWith(u8, name, "reserved") or std.mem.startsWith(u8, name, "pad");
}

fn isMagic(field: model.Field) bool {
    return std.mem.eql(u8, field.name, "magic");
}

fn elementBits(field: model.Field) usize {
    return field.size / field.count * 8;
}

fn findRecord(name: []const u8) RenderError!model.Record {
    return checks.findRecord(model.description, name) orelse error.UnknownRecord;
}

fn fieldAt(record: model.Record, offset: usize) RenderError!model.Field {
    for (record.fields) |field| {
        if (field.offset == offset) return field;
    }
    return error.UnknownField;
}

fn magicBytes(value: u64) []const u8 {
    for (model.description.magics) |magic| {
        if (magic.value == value) return magic.bytes;
    }
    unreachable; // checks.validateChecker ties rule magics to declared magics
}

fn writeBanner(w: *Writer, summary: []const u8) Writer.Error!void {
    try w.print(
        \\%% Generated by tools/abi from interfaces/orchestrator_abi.zig. Do not edit and do not commit.
        \\%% {s}
        \\
    , .{summary});
}

