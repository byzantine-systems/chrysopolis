const helpers =
    \\%% Little-endian unsigned field of Bits bits at byte Offset.
    \\u(Bin, Offset, Bits) ->
    \\    <<_:Offset/binary, Value:Bits/little, _/binary>> = Bin,
    \\    Value.
    \\
    \\zero(Bin, Offset, Zeros) ->
    \\    binary:part(Bin, Offset, byte_size(Zeros)) =:= Zeros.
    \\
    \\published(Seq) ->
    \\    Seq =/= 0 andalso Seq band 1 =:= 0.
    \\
    \\%% A declared zero tag that the rule forbids (`unset` is never published there).
    \\nonzero_member(Member, Value) ->
    \\    Value =/= 0 andalso Member(Value).
    \\
    \\expect(true, _Class) -> ok;
    \\expect(false, Class) -> {error, Class}.
    \\
    \\all_rows(Check, Base, Stride, Count) ->
    \\    lists:all(fun(Row) -> Check(Base + Row * Stride) end, lists:seq(0, Count - 1)).
    \\
    \\%% Published rows only: indexes [Head - min(Head, Cap), Head) in slot Index rem Cap,
    \\%% where Index + 1 is the journal sequence.
    \\all_live(Check, Head, Base, Stride, Cap) ->
    \\    Live = min(Head, Cap),
    \\    lists:all(
    \\        fun(Index) -> Check(Base + (Index rem Cap) * Stride, Index + 1) end,
    \\        lists:seq(Head - Live, Head - 1)
    \\    ).
    \\
    \\live(Rows, Head, Cap) ->
    \\    Slots = list_to_tuple(Rows),
    \\    [element(Index rem Cap + 1, Slots) || Index <- lists:seq(Head - min(Head, Cap), Head - 1)].
    \\
    \\payload_tail(Bin, LengthOffset, LengthBits, PayloadOffset, PayloadSize) ->
    \\    Kept = min(u(Bin, LengthOffset, LengthBits), PayloadSize),
    \\    binary:part(Bin, PayloadOffset + Kept, PayloadSize - Kept) =:= <<0:((PayloadSize - Kept) * 8)>>.
    \\
    \\uint(Value, Bits) when is_integer(Value), Value >= 0, Value < 1 bsl Bits -> Value;
    \\uint(_, _) -> error(badarg).
    \\
    \\bytes(Value, Size) when is_binary(Value), byte_size(Value) =:= Size -> Value;
    \\bytes(_, _) -> error(badarg).
    \\
    \\uints(Values, Count, Bits) when is_list(Values), length(Values) =:= Count ->
    \\    <<<<(uint(V, Bits)):Bits/little>> || V <- Values>>;
    \\uints(_, _, _) -> error(badarg).
    \\
    \\rows(Encode, Values, Count) when is_list(Values), length(Values) =:= Count ->
    \\    <<<<(Encode(V))/binary>> || V <- Values>>;
    \\rows(_, _, _) -> error(badarg).
    \\
;

fn writeExports(w: *Writer) RenderError!void {
    try w.writeAll("-export([layout_digest/0, abi_version/0");
    for (checks.checkers) |checker| {
        try w.print(", check_{s}/{d}", .{ checker.name, @as(u8, if (checker.selector != null) 2 else 1) });
        if (checker.selector != null) continue;
        if (hasSelectorSibling(checker)) {
            try w.print(", decode_{f}/1", .{snake(checker.record)});
        } else {
            try w.print(", decode_{s}/1", .{checker.name});
        }
    }
    for (checks.checkers) |checker| {
        for (checker.rules) |rule| {
            if (rule.check == .crc32) try w.print(", seal_{f}/1", .{snake((try fieldAt(try findRecord(checker.record), rule.scope.selected.base)).element)});
        }
    }
    for (model.description.records) |record| try w.print(", {f}_from_binary/1, {f}_to_binary/1", .{ snake(record.name), snake(record.name) });
    for (model.description.enums) |enumeration| try w.print(", {f}_to_atom/1, {f}_value/1", .{ snake(enumeration.name), snake(enumeration.name) });
    try w.writeAll("]).\n\n");
}

fn writeCodec(w: *Writer) RenderError!void {
    try writeBanner(w, "Checkers, decoders and encoders for the orchestration wire records.");
    try w.writeAll(
        \\-module(chryso_abi_codec).
        \\-moduledoc """
        \\Codec for the orchestration wire records shared with Root and the workers.
        \\
        \\Every `check_*` function is total over any term and returns the same rejection
        \\classes, in the same precedence, as the generated C checkers in
        \\`<chrysopolis/*.h>`: `size`, `magic`, `version`, `torn`, `checksum`, `reserved`,
        \\`unknown_kind`, `range`.
        \\
        \\Decoders take a snapshot that the C side already copied under its seqlock. They
        \\cannot observe shared memory changing, so a torn copy is the caller's to retry.
        \\""".
        \\
        \\-include("orchestrator_abi.hrl").
        \\
        \\
    );
    try writeExports(w);
    try writeTypes(w);
    try w.writeAll(
        \\-doc "CRC-32 of the whole wire model; peers must agree on it before exchanging records.".
        \\-spec layout_digest() -> non_neg_integer().
        \\layout_digest() -> ?CHRYSO_ABI_LAYOUT_DIGEST.
        \\
        \\-doc "Wire ABI version carried in every record header.".
        \\-spec abi_version() -> non_neg_integer().
        \\abi_version() -> ?CHRYSO_ABI_VERSION.
        \\
        \\
    );
    for (checks.checkers) |checker| try writeChecker(w, checker);
    for (checks.checkers) |checker| try writeDecoder(w, checker);
    for (checks.checkers) |checker| try writeSeal(w, checker);
    for (model.description.records) |record| {
        try writeFromBinary(w, record);
        try writeToBinary(w, record);
    }
    for (model.description.enums) |enumeration| try writeEnum(w, enumeration);
    try w.writeAll(helpers);
}

pub const File = struct { path: []const u8, kind: enum { header, codec } };
pub const files = [_]File{
    .{ .path = "include/orchestrator_abi.hrl", .kind = .header },
    .{ .path = "src/chryso_abi_codec.erl", .kind = .codec },
};

/// Caller owns the returned bytes.
pub fn render(allocator: std.mem.Allocator, file: File) (RenderError || std.mem.Allocator.Error)![]u8 {
    var out: Writer.Allocating = .init(allocator);
    defer out.deinit();
    switch (file.kind) {
        .header => try writeHeader(&out.writer),
        .codec => try writeCodec(&out.writer),
    }
    return out.toOwnedSlice();
}

/// Writes `include/` and `src/` under `dir`.
pub fn writeAll(allocator: std.mem.Allocator, dir: std.fs.Dir) !void {
    for (files) |file| {
        const bytes = try render(allocator, file);
        defer allocator.free(bytes);
        if (std.fs.path.dirname(file.path)) |parent| try dir.makePath(parent);
        try dir.writeFile(.{ .sub_path = file.path, .data = bytes });
    }
}

test "rendering is deterministic and carries the shared contract" {
    const allocator = std.testing.allocator;
    const Case = struct { file: File, snippets: []const []const u8 };
    const digest = try std.fmt.allocPrint(allocator, "-define(CHRYSO_ABI_LAYOUT_DIGEST, 16#{x:0>8}).", .{model.layoutDigest(model.description)});
    defer allocator.free(digest);
    const cases = [_]Case{
        .{ .file = files[0], .snippets = &.{
            digest,
            "-define(CHRYSO_MAGIC_STATUS, <<\"CHRYSTA1\">>).",
            "-define(CHRYSO_ROOT_STATUS_PAGE_EVENTS_OFFSET, 5048).",
            "-define(CHRYSO_PP_OPCODE_HELLO, 1).",
        } },
        .{ .file = files[1], .snippets = &.{
            "check_spec_bank(Bin, Bank) when is_binary(Bin), byte_size(Bin) =:= 4096, is_integer(Bank), Bank >= 0, Bank < 2 ->",
            "zero(Bin, 9144, <<0:57920>>)",
            "binary:part(Bin, 0, 8) =:= <<\"CHRYSTA1\">>",
            "-nominal slot_generation() ::",
            "decode_spec_page(Bin) ->",
            "seal_spec_bank(<<",
        } },
    };
    for (cases) |case| {
        const first = try render(allocator, case.file);
        defer allocator.free(first);
        const second = try render(allocator, case.file);
        defer allocator.free(second);
        try std.testing.expectEqualStrings(first, second);
        for (case.snippets) |snippet| {
            if (std.mem.indexOf(u8, first, snippet) == null) {
                std.debug.print("{s} lacks:\n{s}\n", .{ case.file.path, snippet });
                return error.MissingSnippet;
            }
        }
    }
}

