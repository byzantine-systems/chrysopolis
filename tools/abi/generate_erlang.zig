// Validated decoders

fn hasSelectorSibling(checker: checks.Checker) bool {
    for (checks.checkers) |other| {
        if (other.selector != null and std.mem.eql(u8, other.record, checker.record)) return true;
    }
    return false;
}

fn writeDecoder(w: *Writer, checker: checks.Checker) RenderError!void {
    if (checker.selector != null) return; // decoded through its page decoder
    const record = try findRecord(checker.record);
    const record_name = snake(record.name);
    if (hasSelectorSibling(checker)) {
        // Bank validity is per bank: a torn inactive bank must not hide a valid active one.
        var selector: checks.Checker = undefined;
        for (checks.checkers) |other| {
            if (other.selector != null and std.mem.eql(u8, other.record, checker.record)) selector = other;
        }
        const rows = selector.selector.?;
        const bank = try findRecord((try fieldAt(record, rows.base)).element);
        const header = record.fields[0];
        try w.print(
            \\-doc "Checks and decodes a spec page: the header must pass; each bank carries its own verdict.".
            \\-doc #{{group => ~"Decoders"}}.
            \\-spec decode_{f}(binary()) -> {{ok, checked_{f}()}} | {{error, reject()}}.
            \\decode_{f}(Bin) ->
            \\    maybe
            \\        ok ?= check_{s}(Bin),
            \\        {{ok, #{{{s} => {f}_from_binary(binary:part(Bin, {d}, {d})),
            \\               banks => [case check_{s}(Bin, I) of
            \\                             ok -> {{ok, {f}_from_binary(binary:part(Bin, {d} + I * {d}, {d}))}};
            \\                             Error -> Error
            \\                         end || I <- lists:seq(0, {d})]}}}}
            \\    end.
            \\
            \\
        , .{
            record_name,           record_name,   record_name, checker.name,   header.name,
            snake(header.element), header.offset, header.size, selector.name,  snake(bank.name),
            rows.base,             rows.stride,   rows.stride, rows.count - 1,
        });
        return;
    }
    try w.print(
        \\-doc "Checks and decodes a `{s}` snapshot. Published windows hold only live rows, oldest first.".
        \\-doc #{{group => ~"Decoders"}}.
        \\-spec decode_{s}(binary()) -> {{ok, {f}()}} | {{error, reject()}}.
        \\decode_{s}(Bin) ->
        \\    maybe
        \\        ok ?= check_{s}(Bin),
        \\        Page = {f}_from_binary(Bin),
        \\
    , .{ checker.name, checker.name, record_name, checker.name, checker.name, record_name });
    // A published window returns only its live rows, oldest first.
    var window: ?checks.Window = null;
    var tail: ?checks.PayloadTail = null;
    for (checker.rules) |rule| {
        if (rule.scope == .window) window = rule.scope.window;
        if (rule.check == .payload_tail) tail = rule.check.payload_tail;
    }
    if (window) |live| {
        const field = try fieldAt(record, live.base);
        try w.print("        Live = live(maps:get({s}, Page), u(Bin, {d}, 64), {d}),\n", .{ field.name, live.head_offset, live.capacity });
        if (tail) |payload| {
            const entry = try findRecord(field.element);
            const length = try fieldAt(entry, payload.length.offset);
            const bytes = try fieldAt(entry, payload.payload.offset);
            try w.print(
                \\        Trimmed = [E#{{{s} := binary:part(maps:get({s}, E), 0, maps:get({s}, E))}} || E <- Live],
                \\        {{ok, Page#{{{s} := Trimmed}}}}
                \\
            , .{ bytes.name, bytes.name, length.name, field.name });
        } else {
            try w.print("        {{ok, Page#{{{s} := Live}}}}\n", .{field.name});
        }
    } else {
        try w.writeAll("        {ok, Page}\n");
    }
    try w.writeAll("    end.\n\n");
}

