fn writeFromBinary(w: *Writer, record: model.Record) Writer.Error!void {
    const name = snake(record.name);
    try w.print("-doc \"Unchecked field decode of a {d}-byte `{s}`; run the checker first for untrusted input.\".\n", .{ record.size, record.name });
    try w.writeAll("-doc #{group => ~\"Records\"}.\n");
    try w.print("-spec {f}_from_binary(binary()) -> {f}().\n{f}_from_binary(<<", .{ name, name, name });
    for (record.fields, 0..) |field, i| {
        if (i != 0) try w.writeAll(", ");
        if (isReserved(field.name)) {
            try w.print("_:{d}/binary", .{field.size});
        } else if (isMagic(field) or field.is_record or field.count > 1) {
            try w.print("{f}:{d}/binary", .{ camel(field.name), field.size });
        } else {
            try w.print("{f}:{d}/little", .{ camel(field.name), elementBits(field) });
        }
    }
    // One multi-field pattern binds every field, so the compiler keeps a single match context.
    try w.writeAll(">>) ->\n    #{");
    var first = true;
    for (record.fields) |field| {
        if (isReserved(field.name)) continue;
        if (!first) try w.writeAll(",\n      ");
        first = false;
        try w.print("{s} => ", .{field.name});
        const v = camel(field.name);
        if (isMagic(field)) {
            try w.print("{f}", .{v});
        } else if (field.is_record and field.count == 1) {
            try w.print("{f}_from_binary({f})", .{ snake(field.element), v });
        } else if (field.is_record) {
            try w.print("[{f}_from_binary(E) || <<E:{d}/binary>> <= {f}]", .{ snake(field.element), field.size / field.count, v });
        } else if (field.count > 1 and elementBits(field) == 8) {
            // A copy, so a small field never pins the whole page binary.
            try w.print("binary:copy({f})", .{v});
        } else if (field.count > 1) {
            try w.print("[E || <<E:{d}/little>> <= {f}]", .{ elementBits(field), v });
        } else {
            try w.print("{f}", .{v});
        }
    }
    try w.writeAll("\n    }.\n\n");
}

fn writeToBinary(w: *Writer, record: model.Record) Writer.Error!void {
    const name = snake(record.name);
    try w.print("-doc \"Encodes a `{s}` with zeroed reserved bytes. Raises `badarg` on an out-of-range field.\".\n", .{record.name});
    try w.writeAll("-doc #{group => ~\"Records\"}.\n");
    try w.print("-spec {f}_to_binary({f}()) -> binary().\n{f}_to_binary(#{{", .{ name, name, name });
    var first = true;
    for (record.fields) |field| {
        if (isReserved(field.name)) continue;
        if (!first) try w.writeAll(", ");
        first = false;
        try w.print("{s} := {f}", .{ field.name, camel(field.name) });
    }
    try w.writeAll("}) ->\n    <<");
    for (record.fields, 0..) |field, i| {
        if (i != 0) try w.writeAll(",\n      ");
        const v = camel(field.name);
        if (isReserved(field.name)) {
            try w.print("0:{d}", .{field.size * 8});
        } else if (isMagic(field)) {
            try w.print("(bytes({f}, 8))/binary", .{v});
        } else if (field.is_record and field.count == 1) {
            try w.print("({f}_to_binary({f}))/binary", .{ snake(field.element), v });
        } else if (field.is_record) {
            try w.print("(rows(fun {f}_to_binary/1, {f}, {d}))/binary", .{ snake(field.element), v, field.count });
        } else if (field.count > 1 and elementBits(field) == 8) {
            try w.print("(bytes({f}, {d}))/binary", .{ v, field.count });
        } else if (field.count > 1) {
            try w.print("(uints({f}, {d}, {d}))/binary", .{ v, field.count, elementBits(field) });
        } else {
            try w.print("(uint({f}, {d})):{d}/little", .{ v, elementBits(field), elementBits(field) });
        }
    }
    try w.writeAll(">>.\n\n");
}

/// `seal_<record>/1` for each CRC rule: fills in the CRC, reading the zeroed spans as zero.
fn writeSeal(w: *Writer, checker: checks.Checker) RenderError!void {
    const page = try findRecord(checker.record);
    for (checker.rules) |rule| {
        if (rule.check != .crc32) continue;
        const crc = rule.check.crc32;
        const rows = rule.scope.selected;
        const bank = try findRecord((try fieldAt(page, rows.base)).element);
        const name = snake(bank.name);
        // Pieces between the stored CRC and the zeroed spans, in offset order.
        const Piece = struct { offset: usize, len: usize, kind: enum { keep, crc, zeroed } };
        var pieces: [8]Piece = undefined;
        var count: usize = 0;
        var cursor: usize = crc.span.offset;
        const stored = [_]checks.Span{.{ .offset = crc.crc.offset, .len = crc.crc.width }};
        for ([_][]const checks.Span{ &stored, crc.zeroed }, 0..) |group, g| {
            for (group) |span| {
                if (span.offset > cursor) {
                    pieces[count] = .{ .offset = cursor, .len = span.offset - cursor, .kind = .keep };
                    count += 1;
                }
                pieces[count] = .{ .offset = span.offset, .len = span.len, .kind = if (g == 0) .crc else .zeroed };
                count += 1;
                cursor = span.offset + span.len;
            }
        }
        const end = crc.span.offset + crc.span.len;
        if (end > cursor) {
            pieces[count] = .{ .offset = cursor, .len = end - cursor, .kind = .keep };
            count += 1;
        }
        try w.print("-doc \"Stores the CRC-32 of a `{s}`, computed with the CRC and zeroed fields read as zero.\".\n", .{bank.name});
        try w.writeAll("-doc #{group => ~\"Records\"}.\n");
        try w.print("-spec seal_{f}(binary()) -> binary().\nseal_{f}(<<", .{ name, name });
        for (pieces[0..count], 0..) |piece, i| {
            if (i != 0) try w.writeAll(", ");
            switch (piece.kind) {
                .crc => try w.print("_:{d}", .{piece.len * 8}),
                .keep, .zeroed => try w.print("P{d}:{d}/binary", .{ i, piece.len }),
            }
        }
        try w.writeAll(">>) ->\n    Crc = erlang:crc32([");
        for (pieces[0..count], 0..) |piece, i| {
            if (i != 0) try w.writeAll(", ");
            switch (piece.kind) {
                .keep => try w.print("P{d}", .{i}),
                .crc, .zeroed => try w.print("<<0:{d}>>", .{piece.len * 8}),
            }
        }
        try w.writeAll("]),\n    <<");
        for (pieces[0..count], 0..) |piece, i| {
            if (i != 0) try w.writeAll(", ");
            switch (piece.kind) {
                .crc => try w.print("Crc:{d}/little", .{piece.len * 8}),
                .keep, .zeroed => try w.print("P{d}/binary", .{i}),
            }
        }
        try w.writeAll(">>.\n\n");
    }
}

