// Enums

fn writeEnum(w: *Writer, enumeration: model.Enum) Writer.Error!void {
    const name = snake(enumeration.name);
    try w.print("-doc \"The `{s}` tag for a wire value, or `error` for an undeclared one.\".\n", .{enumeration.name});
    try w.writeAll("-doc #{group => ~\"Enums\"}.\n");
    try w.print("-spec {f}_to_atom(non_neg_integer()) -> {{ok, {f}()}} | error.\n", .{ name, name });
    for (enumeration.values) |value| try w.print("{f}_to_atom({d}) -> {{ok, {s}}};\n", .{ name, value.value, value.name });
    try w.print("{f}_to_atom(_) -> error.\n\n", .{name});
    try w.print("-doc \"The wire value of a `{s}` tag.\".\n", .{enumeration.name});
    try w.writeAll("-doc #{group => ~\"Enums\"}.\n");
    try w.print("-spec {f}_value({f}()) -> non_neg_integer().\n", .{ name, name });
    for (enumeration.values, 0..) |value, i| {
        try w.print("{f}_value({s}) -> {d}{s}\n", .{ name, value.name, value.value, if (i + 1 == enumeration.values.len) "." else ";" });
    }
    try w.writeByte('\n');
    if (!enumeration.wire) return;
    for (enumeration.values) |value| try w.print("is_{f}({d}) -> true;\n", .{ name, value.value });
    try w.print("is_{f}(_) -> false.\n\n", .{name});
}

