// Types

fn writeScalarType(w: *Writer, bits: usize) Writer.Error!void {
    try w.print("0..{d}", .{(@as(u128, 1) << @as(u7, @intCast(bits))) - 1});
}

fn writeFieldType(w: *Writer, record: model.Record, field: model.Field) Writer.Error!void {
    if (isMagic(field)) return w.writeAll("<<_:64>>");
    if (field.is_record) {
        if (field.count == 1) return w.print("{f}()", .{snake(field.element)});
        return w.print("[{f}()]", .{snake(field.element)});
    }
    if (field.count > 1 and elementBits(field) == 8) return w.writeAll("binary()");
    if (field.count > 1) {
        try w.writeByte('[');
        try writeScalarType(w, elementBits(field));
        return w.writeByte(']');
    }
    if (nominalFor(record.name, field.name)) |nominal| return w.print("{s}()", .{nominal});
    try writeScalarType(w, elementBits(field));
}

fn writeTypes(w: *Writer) RenderError!void {
    try w.writeAll(
        \\-doc "Why a snapshot was rejected; the same classes and precedence as the C checkers.".
        \\-type reject() :: size | magic | version | torn | checksum | reserved | unknown_kind | range.
        \\-doc "Generation of a published spec bank. Nominal, so it cannot be mixed with a slot generation.".
        \\-nominal spec_generation() :: 0..18446744073709551615.
        \\-doc "Generation of a pool slot's occupant, used to fence stale workers and journals.".
        \\-nominal slot_generation() :: 0..18446744073709551615.
        \\
    );
    for (model.description.records) |record| {
        try w.print("-doc \"The `{s}` wire record ({d} bytes) with reserved fields omitted.\".\n", .{ record.name, record.size });
        try w.print("-type {f}() :: #{{\n", .{snake(record.name)});
        var first = true;
        for (record.fields) |field| {
            if (isReserved(field.name)) continue;
            if (!first) try w.writeAll(",\n");
            first = false;
            try w.print("    {s} := ", .{field.name});
            try writeFieldType(w, record, field);
        }
        try w.writeAll("\n}.\n");
    }
    for (model.description.enums) |enumeration| {
        try w.print("-doc \"Tags of `{s}`.\".\n", .{enumeration.name});
        try w.print("-type {f}() :: ", .{snake(enumeration.name)});
        for (enumeration.values, 0..) |value, i| {
            if (i != 0) try w.writeAll(" | ");
            try w.writeAll(value.name);
        }
        try w.writeAll(".\n");
    }
    try w.writeAll(
        \\-doc "A spec page whose header passed, with each bank's own verdict.".
        \\-type checked_spec_page() :: #{header := spec_header(), banks := [{ok, spec_bank()} | {error, reject()}]}.
        \\
        \\-export_type([reject/0, spec_generation/0, slot_generation/0, checked_spec_page/0
    );
    for (model.description.records) |record| try w.print(", {f}/0", .{snake(record.name)});
    for (model.description.enums) |enumeration| try w.print(", {f}/0", .{snake(enumeration.name)});
    try w.writeAll("]).\n\n");
}

