/// Offset expression of a rule field: absolute for whole scope, `At + n` inside rows and windows.
const Offset = struct {
    base: ?[]const u8,
    value: usize,
    pub fn format(self: Offset, w: *Writer) Writer.Error!void {
        if (self.base) |base| {
            if (self.value == 0) return w.writeAll(base);
            return w.print("{s} + {d}", .{ base, self.value });
        }
        try w.print("{d}", .{self.value});
    }
};

fn writeLoad(w: *Writer, base: ?[]const u8, int: checks.Int) Writer.Error!void {
    try w.print("u(Bin, {f}, {d})", .{ Offset{ .base = base, .value = int.offset }, int.width * 8 });
}

fn writeZero(w: *Writer, base: ?[]const u8, offset: usize, len: usize) Writer.Error!void {
    // The literal is a constant term, so the comparison allocates nothing.
    try w.print("zero(Bin, {f}, <<0:{d}>>)", .{ Offset{ .base = base, .value = offset }, len * 8 });
}

/// A boolean Erlang expression that holds when the rule holds at this scope instance.
fn writeCondition(w: *Writer, check: checks.Check, base: ?[]const u8) RenderError!void {
    switch (check) {
        .magic => |value| try w.print("binary:part(Bin, {f}, 8) =:= <<\"{s}\">>", .{ Offset{ .base = base, .value = value.int.offset }, magicBytes(value.value) }),
        .version, .equal => |value| {
            try writeLoad(w, base, value.int);
            try w.print(" =:= {d}", .{value.value});
        },
        .at_most => |value| {
            try writeLoad(w, base, value.int);
            try w.print(" =< {d}", .{value.value});
        },
        .ring_dropped => |value| {
            try writeLoad(w, base, value.dropped);
            try w.writeAll(" =:= erlang:max(0, ");
            try writeLoad(w, base, value.head);
            try w.print(" - {d})", .{value.capacity});
        },
        .event_child => |value| {
            try w.writeAll("(case ");
            try writeLoad(w, base, value.kind);
            try w.writeAll(" of ");
            for (value.global) |kind| {
                try w.print("{d} -> ", .{kind});
                try writeLoad(w, base, value.child);
                try w.print(" =:= {d}; ", .{value.sentinel});
            }
            try w.writeAll("_ -> (");
            try writeLoad(w, base, value.child);
            try w.print(" < {d} andalso u(Bin, {d} + ", .{ value.targets.count, value.targets.base });
            try writeLoad(w, base, value.child);
            try w.print(" * {d} + {d}, 8) =/= 0) end)", .{ value.targets.stride, value.target_state.offset });
        },
        .only_for_kind => |value| {
            try w.writeByte('(');
            try writeLoad(w, base, value.int);
            try w.writeAll(" =:= 0 orelse ");
            try writeLoad(w, base, value.kind);
            try w.print(" =:= {d})", .{value.value});
        },
        .implies => |value| {
            try w.writeByte('(');
            try writeLoad(w, base, value.int);
            try w.print(" band {d} =:= 0 orelse ", .{value.when});
            try writeLoad(w, base, value.int);
            try w.print(" band {d} =:= {d})", .{ value.requires, value.requires });
        },
        .zero_when_unset => |value| {
            try w.writeByte('(');
            try writeLoad(w, base, value.int);
            try w.writeAll(" =/= 0 orelse ");
            try writeZero(w, base, value.span.offset, value.span.len);
            try w.writeByte(')');
        },
        .kind_member => |value| {
            try w.writeByte('(');
            try writeLoad(w, base, value.kind);
            try w.print(" =/= {d} orelse ", .{value.value});
            try writeCondition(w, .{ .member = value.member }, base);
            try w.writeByte(')');
        },
        .seqlock => |value| {
            try w.writeAll("published(");
            try writeLoad(w, base, value);
            try w.writeAll(")");
        },
        .nonzero => |value| {
            try writeLoad(w, base, value);
            try w.writeAll(" =/= 0");
        },
        .zero => |value| try writeZero(w, base, value.offset, value.len),
        .member => |value| {
            if (value.reject_zero) {
                try w.print("nonzero_member(fun is_{f}/1, ", .{snake(value.enumeration)});
            } else {
                try w.print("is_{f}(", .{snake(value.enumeration)});
            }
            try writeLoad(w, base, value.int);
            try w.writeAll(")");
        },
        .crc32 => |value| {
            try w.writeAll("erlang:crc32([");
            var cursor = value.span.offset;
            var first = true;
            const stored = [_]checks.Span{.{ .offset = value.crc.offset, .len = value.crc.width }};
            for ([_][]const checks.Span{ &stored, value.zeroed }) |group| {
                for (group) |zeroed| {
                    if (zeroed.offset > cursor) {
                        if (!first) try w.writeAll(", ");
                        try w.print("binary:part(Bin, {f}, {d})", .{ Offset{ .base = base, .value = cursor }, zeroed.offset - cursor });
                        first = false;
                    }
                    if (!first) try w.writeAll(", ");
                    try w.print("<<0:{d}>>", .{zeroed.len * 8});
                    first = false;
                    cursor = zeroed.offset + zeroed.len;
                }
            }
            const end = value.span.offset + value.span.len;
            if (end > cursor) try w.print(", binary:part(Bin, {f}, {d})", .{ Offset{ .base = base, .value = cursor }, end - cursor });
            try w.writeAll("]) =:= ");
            try writeLoad(w, base, value.crc);
        },
        .entry_identity => |value| {
            try writeLoad(w, base, value.generation);
            try w.print(" =:= u(Bin, {d}, 64) andalso ", .{value.header_generation});
            try writeLoad(w, base, value.sequence);
            try w.writeAll(" =:= Seq");
        },
        .payload_tail => |value| try w.print("payload_tail(Bin, {f}, {d}, {f}, {d})", .{
            Offset{ .base = base, .value = value.length.offset },  value.length.width * 8,
            Offset{ .base = base, .value = value.payload.offset }, value.payload.len,
        }),
    }
}

fn usesSequence(group: []const checks.Rule) bool {
    for (group) |rule| {
        if (rule.check == .entry_identity) return true;
    }
    return false;
}

fn writeConditions(w: *Writer, group: []const checks.Rule, base: ?[]const u8) RenderError!void {
    for (group, 0..) |rule, i| {
        if (i != 0) try w.writeAll(" andalso\n            ");
        try writeCondition(w, rule.check, base);
    }
}

/// One `ok ?= expect(..., Class)` line per group of rules sharing class and scope.
fn writeGroup(w: *Writer, group: []const checks.Rule) RenderError!void {
    const class = @tagName(group[0].class);
    try w.writeAll("        ok ?= expect(");
    switch (group[0].scope) {
        .whole => try writeConditions(w, group, null),
        .selected => try writeConditions(w, group, "At"),
        .rows => |rows| {
            try w.writeAll("all_rows(fun(At) ->\n            ");
            try writeConditions(w, group, "At");
            try w.print("\n        end, {d}, {d}, {d})", .{ rows.base, rows.stride, rows.count });
        },
        .window => |window| {
            try w.print("all_live(fun(At, {s}) ->\n            ", .{if (usesSequence(group)) "Seq" else "_Seq"});
            try writeConditions(w, group, "At");
            try w.print("\n        end, u(Bin, {d}, 64), {d}, {d}, {d})", .{ window.head_offset, window.base, window.stride, window.capacity });
        },
    }
    try w.print(", {s})", .{class});
}

fn writeChecker(w: *Writer, checker: checks.Checker) RenderError!void {
    const name = checker.name;
    if (checker.selector) |selector| {
        try w.print(
            \\-doc """
            \\Checks bank `Bank` of a `{s}` snapshot. An invalid index is `range`; the other bank
            \\is not examined, so a torn inactive bank never hides a committed active one.
            \\""".
            \\-doc #{{group => ~"Checkers"}}.
            \\-spec check_{s}(term(), term()) -> ok | {{error, reject()}}.
            \\check_{s}(Bin, Bank) when is_binary(Bin), byte_size(Bin) =:= {d}, is_integer(Bank), Bank >= 0, Bank < {d} ->
            \\    At = {d} + Bank * {d},
            \\
        , .{ checker.record, name, name, checker.size, selector.count, selector.base, selector.stride });
    } else {
        try w.print(
            \\-doc """
            \\Checks a `{s}` snapshot of exactly {d} bytes. Returns the highest-precedence
            \\violation, or `ok`. Total over any term.
            \\""".
            \\-doc #{{group => ~"Checkers"}}.
            \\-spec check_{s}(term()) -> ok | {{error, reject()}}.
            \\check_{s}(Bin) when is_binary(Bin), byte_size(Bin) =:= {d} ->
            \\
        , .{ checker.record, checker.size, name, name, checker.size });
    }
    try w.writeAll("    maybe\n");
    var start: usize = 0;
    var first = true;
    while (start < checker.rules.len) {
        var end = start + 1;
        while (end < checker.rules.len and checker.rules[end].class == checker.rules[start].class and
            std.meta.eql(checker.rules[end].scope, checker.rules[start].scope)) end += 1;
        if (!first) try w.writeAll(",\n");
        first = false;
        try writeGroup(w, checker.rules[start..end]);
        start = end;
    }
    try w.writeAll("\n    end;\n");
    if (checker.selector != null) {
        try w.print(
            \\check_{s}(Bin, _Bank) when is_binary(Bin), byte_size(Bin) =:= {d} ->
            \\    {{error, range}};
            \\check_{s}(_Bin, _Bank) ->
            \\    {{error, size}}.
            \\
            \\
        , .{ name, checker.size, name });
    } else {
        try w.print("check_{s}(_Bin) ->\n    {{error, size}}.\n\n", .{name});
    }
}

