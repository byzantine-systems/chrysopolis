fn writeHeader(w: *Writer) RenderError!void {
    const d = model.description;
    try writeBanner(w, "Constants shared with the C contract in <chrysopolis/orchestrator_abi.h>.");
    try w.writeAll("-ifndef(CHRYSO_ORCHESTRATOR_ABI_HRL).\n-define(CHRYSO_ORCHESTRATOR_ABI_HRL, true).\n\n");
    try w.print("-define(CHRYSO_ABI_VERSION, {d}).\n", .{d.abi_version});
    try w.print("-define(CHRYSO_ABI_LAYOUT_DIGEST, 16#{x:0>8}).\n", .{model.layoutDigest(d)});
    try w.print("-define(CHRYSO_CHILD_COUNT, {d}).\n", .{d.constants.child_count});
    try w.print("-define(CHRYSO_EVENT_COUNT, {d}).\n", .{d.constants.event_count});
    try w.print("-define(CHRYSO_JOURNAL_CAPACITY, {d}).\n", .{d.constants.journal_capacity});
    try w.print("-define(CHRYSO_JOURNAL_PAYLOAD_SIZE, {d}).\n", .{d.constants.journal_payload_size});
    try w.print("-define(CHRYSO_ROOT_EVENT_NO_CHILD, {d}).\n", .{d.constants.root_event_no_child});
    try w.print("-define(CHRYSO_FAULT_MR0_VALID, {d}).\n", .{d.constants.fault_mr0_valid});
    try w.print("-define(CHRYSO_FAULT_MR1_VALID, {d}).\n", .{d.constants.fault_mr1_valid});
    try w.print("-define(CHRYSO_DOWN_INTERVAL_OPEN, {d}).\n\n", .{d.constants.down_interval_open});
    for (d.magics) |magic| {
        try w.print("-define(CHRYSO_MAGIC_{f}, <<\"{s}\">>).\n", .{ upper(magic.name), magic.bytes });
    }
    try w.writeByte('\n');
    for (d.records) |record| {
        try w.print("-define(CHRYSO_{f}_SIZE, {d}).\n", .{ upper(record.name), record.size });
        for (record.fields) |field| {
            try w.print("-define(CHRYSO_{f}_{f}_OFFSET, {d}).\n", .{ upper(record.name), upper(field.name), field.offset });
        }
    }
    try w.writeByte('\n');
    for (d.enums) |enumeration| {
        for (enumeration.values) |value| {
            try w.print("-define(CHRYSO_{f}_{f}, {d}).\n", .{ upper(enumeration.name), upper(value.name), value.value });
        }
    }
    try w.writeAll("\n-endif.\n");
}

