//! C23 headers for the orchestration ABI, emitted into a build directory and never committed.
//! Layout asserts come from the extern structs; checkers from checks.zig. Output includes only
//! <stdint.h> <stddef.h> <stdbool.h> <stdatomic.h> and reads bytes without casting to records.
const std = @import("std");
const system = @import("system_abi");
const abi = @import("orchestrator_abi");
const model = @import("model");
const checks = @import("checks");

const Writer = std.Io.Writer;

